#!/usr/bin/env python3
"""Small-block delta regressions and H1/H2 counterexample-pattern tests.

Inputs are read-only. All generated bytes and receipts go to --out, outside
this source tree. No external producer verdict is trusted by this driver.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import subprocess
import time


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    for name in ("exe", "m2", "m4", "wierman", "probes", "out"):
        ap.add_argument("--" + name, type=Path, required=True)
    a = ap.parse_args()
    a.exe = a.exe.resolve()
    a.out.mkdir(parents=True, exist_ok=True)
    results = []
    inputs = {}
    for d in (a.m2, a.m4, a.wierman):
        for p in sorted(d.glob("*.bin")):
            inputs[str(p)] = sha(p)
    probes = {p.name: sha(p) for p in a.probes.glob("siteperc_*probe.py")}

    def run(name, argv, rc, needle):
        t = time.monotonic()
        r = subprocess.run([str(a.exe)] + list(map(str, argv)), text=True,
                           capture_output=True, timeout=30)
        log = r.stdout + r.stderr
        (a.out / (name + ".log")).write_text(log)
        result = {"name": name, "args": list(map(str, argv)),
                  "returncode": r.returncode, "expected_returncode": rc,
                  "required_output": needle, "wall_s": time.monotonic() - t,
                  "pass": r.returncode == rc and needle in log,
                  "log_sha256": hashlib.sha256(log.encode()).hexdigest()}
        results.append(result)
        return result

    for m, d in ((2, a.m2), (4, a.m4)):
        run("m%d_final_actual" % m,
            ["certify", m, 1, d / "laws.bin", d / "s1ok_nodes.bin",
             d / "s1ok_edges.bin", d / "s2ok_nodes.bin", d / "s2ok_edges.bin"],
            0, "C1_C6_FLOW_PASS stage=2")
    run("wierman1995_final_actual",
        ["certify", 2, 1, a.wierman / "laws.bin", a.wierman / "s1_nodes.bin",
         a.wierman / "s1_edges.bin", a.wierman / "s2_nodes.bin",
         a.wierman / "s2_edges.bin", "wierman1995"],
        0, "C1_C6_FLOW_PASS stage=2")

    for m, d in ((2, a.m2), (4, a.m4)):
        run("m%d_direct_actual" % m,
            ["direct", m, 4, d / "s1ok_nodes.bin", d / "s1ok_edges.bin",
             d / "s2ok_nodes.bin", d / "s2ok_edges.bin"],
            0, "DIRECT_C7_C1_C6_PASS")
    run("wierman1995_direct_actual",
        ["direct", 2, 4, a.wierman / "s1_nodes.bin", a.wierman / "s1_edges.bin",
         a.wierman / "s2_nodes.bin", a.wierman / "s2_edges.bin", "wierman1995"],
        0, "DIRECT_C7_C1_C6_PASS")

    empty_edges = a.out / "empty_edges.bin"
    empty_edges.write_bytes(b"R10AEDGE" + struct.pack("<Q", 0))
    # H1: one nominal row, no law support, and a dummy all-closed node.
    empty_laws = a.out / "empty_laws.bin"
    empty_laws.write_bytes(struct.pack("<IIIQ", 4, 4, 3, 1) + bytes(16 + 3 * 5 * 8))
    N = 1 << 100
    dummy = []
    for col, num, den in ((1, 586668, 1000000), (2, 679493, 1000000)):
        p = a.out / ("dummy_s%d_nodes.bin" % col)
        capacity = N * (den - num) ** 4 // den ** 4
        body = bytes(16) + bytes(16) + capacity.to_bytes(16, "little") + bytes(16)
        p.write_bytes(b"R10ANODE" + struct.pack("<IIQII", 4, 4, 1, col, 0) + body)
        dummy.append(p)
    args = [2, 1, empty_laws, dummy[0], empty_edges, dummy[1], empty_edges]
    run("H1_empty_law", ["certify"] + args, 2, "pass=false")
    args[2] = a.m2 / "laws.bin"
    run("H1_omitted_nonbottom", ["flow"] + args, 3, "C6 missing source")

    # H2 patterns preserve the real input's other bytes. Moving an invalid row
    # to the front makes C1, not a later mass mismatch, the decisive check.
    base = bytearray((a.m2 / "s1ok_nodes.bin").read_bytes())
    first = int.from_bytes(base[32:48], "little")
    for name, key in (("H2_noncanonical_orbit", 32),
                      ("H2_ignored_high_bit", first + (1 << 20))):
        data = bytearray(base)
        data[32:48] = key.to_bytes(16, "little")
        p = a.out / (name + "_nodes.bin")
        p.write_bytes(data)
        run(name, ["flow", 2, 1, a.m2 / "laws.bin", p,
                   a.m2 / "s1ok_edges.bin", a.m2 / "s2ok_nodes.bin",
                   a.m2 / "s2ok_edges.bin"], 3, "C1/C4/C5 nodes")
    data = bytearray(base)
    data[96:160] = data[32:96]
    p = a.out / "H2_duplicate_key_nodes.bin"
    p.write_bytes(data)
    run("H2_duplicate_key", ["flow", 2, 1, a.m2 / "laws.bin", p,
                             a.m2 / "s1ok_edges.bin", a.m2 / "s2ok_nodes.bin",
                             a.m2 / "s2ok_edges.bin"], 3, "C1 duplicate key")
    p = a.out / "zero_nodes.bin"
    p.write_bytes(b"R10ANODE" + struct.pack("<IIQII", 4, 4, 0, 1, 0))
    run("zero_node_count", ["flow", 2, 1, a.m2 / "laws.bin", p, empty_edges,
                            a.m2 / "s2ok_nodes.bin", a.m2 / "s2ok_edges.bin"],
        3, "node shape or columns")
    after = {p: sha(p) for p in inputs}
    receipt = {"binary_sha256": sha(a.exe), "inputs_sha256": inputs,
               "input_bytes_unchanged": inputs == after,
               "probe_sources_sha256": probes,
               "probe_scope": "H1/H2 source patterns instantiated at 2x2; original 6x6 probe scripts not executed or modified.",
               "results": results,
               "all_pass": all(r["pass"] for r in results) and inputs == after}
    (a.out / "REGRESSION.json").write_text(json.dumps(receipt, indent=2) + "\n")
    print(json.dumps({"all_pass": receipt["all_pass"], "cases": len(results),
                      "binary_sha256": receipt["binary_sha256"],
                      "summary": [{"name": r["name"], "rc": r["returncode"],
                                   "pass": r["pass"]} for r in results]}, indent=2))
    return 0 if receipt["all_pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
