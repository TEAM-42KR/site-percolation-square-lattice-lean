#!/usr/bin/env python3
"""Emit the optional final native theorem module without running its computation.

The generated module imports externally supplied pure flow-byte constants. It
contains one native_decide for the full direct-law predicate, followed by the
two mathematical conclusions. Generating this source is not a computation PASS.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(data_module: str, workers: int) -> str:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*(?:\.[A-Za-z_][A-Za-z_0-9]*)*", data_module):
        raise ValueError("data module must be a Lean module identifier")
    if workers < 1:
        raise ValueError("workers must be positive")
    road_source = (ROOT / "SitePerc/Road.lean").read_text()
    marker = "theorem SitePercUpper.Lean.RoadMain\n"
    if road_source.count(marker) != 1:
        raise ValueError("unique proved RoadMain source declaration is required")
    road_type = road_source.split(marker, 1)[1].split(" := by", 1)[0]
    site_binder = "    (hsite : SitePerc.pcSite ≤ (79 / 125 : ℝ)) :"
    if road_type.count(site_binder) != 1:
        raise ValueError("RoadMain site-bound interface changed; inspect before generation")
    road_type = road_type.replace(site_binder, "    :", 1)
    vals = " ".join(f"{data_module}.{n}" for n in ("s1Nodes", "s1Edges", "s2Nodes", "s2Edges"))
    return f'''import SitePerc.Checker.DirectSoundness
import SitePerc.Conditional
import SitePerc.Road
import {data_module}
import Lean.Elab.Tactic.Decide

/-!
# Optional final certificate computation and mathematical consequences

This source is generated, not an execution receipt. Its full computation must
compile successfully before any of the declarations below are claimed.
There is exactly one native decision of the complete direct-law predicate;
the probability laws are generated by Lean, never read from producer data.
The native trust boundary is disclosed by the three axiom prints below.
-/

namespace SitePercUpper.Lean

set_option maxRecDepth 1000000
set_option maxHeartbeats 0

/-- One complete direct-law enumeration and two exact flow checks. -/
theorem six_by_six_native_success :
    SitePerc.Checker.directRegionalPass 6 {workers}
      SitePerc.Checker.verifiedStageOneParams SitePerc.Checker.verifiedStageTwoParams
      {vals} = true := by
  native_decide

/-- Square-lattice site upper bound with only the named Kesten input. -/
theorem SiteUpper (kesten : SitePerc.KestenAboveHalf) :
    SitePerc.pcSite ≤ (79 / 125 : ℝ) := by
  have hd := SitePerc.Checker.directRegionalPass_boundary_stages {workers}
    {vals} six_by_six_native_success
  exact SitePerc.site_upper_of_boundary_domination kesten ⟨hd.1, hd.2⟩

/-- Full road theorem and corollaries, including c = 1, using SiteUpper above. -/
theorem RoadMainCertified
    (kesten : SitePerc.KestenAboveHalf)
{road_type} := by
  exact SitePercUpper.Lean.RoadMain density continuous tail lower (SiteUpper kesten)

#print axioms six_by_six_native_success
#print axioms SiteUpper
#print axioms RoadMainCertified

end SitePercUpper.Lean
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-module", default="SitePercCompactCertificateData")
    parser.add_argument("--workers", type=int, default=192)
    parser.add_argument("--output", type=Path, default=ROOT / "SitePerc/Final.lean")
    args = parser.parse_args()
    text = render(args.data_module, args.workers)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text)
    print(json.dumps({"generated": str(args.output), "source_sha256": hashlib.sha256(text.encode()).hexdigest(),
                      "native_decision_count": text.count("\n  native_decide\n"),
                      "executed": False, "proof_status": "NOT_COMPILED"}, indent=2))


if __name__ == "__main__":
    main()
